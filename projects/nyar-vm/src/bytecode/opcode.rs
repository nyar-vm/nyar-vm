#[repr(u8)]
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Opcode {
    Nop = 0x00,
    Push = 0x01,
    Pop = 0x02,
    Dup = 0x03,
    Swap = 0x04,
    LoadLocal = 0x05,
    StoreLocal = 0x06,
    LoadGlobal = 0x07,
    StoreGlobal = 0x08,
    LoadUpvalue = 0x09,
    StoreUpvalue = 0x0A,
    CloseUpvalues = 0x0B,
    Jump = 0x10,
    JumpIfFalse = 0x11,
    JumpIfNull = 0x12,
    Return = 0x13,

    Call = 0x20,
    CallVirtual = 0x21,
    CallDynamic = 0x22,
    FFICall = 0xF0,
    TailCall = 0x14,

    GetField = 0x30,
    SetField = 0x31,
    NewObject = 0x32,
    NewArray = 0x33,
    GetElement = 0x34,
    SetElement = 0x35,
    TypeOf = 0x40,
    InstanceOf = 0x41,
    CheckCast = 0x42,
    Cast = 0x43,
    Perform = 0x50,
    WithHandler = 0x51,
    ResumeWith = 0x52,
    CaptureCont = 0x53,
    GetWitnessTable = 0x60,
    WitnessMethod = 0x61,
    OpenExistential = 0x62,
    CloseExistential = 0x63,
    Quote = 0x70,
    Splice = 0x71,
    Eval = 0x72,
    ExpandMacro = 0x73,

    Halt = 0xFF,
}
